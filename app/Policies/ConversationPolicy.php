<?php

namespace App\Policies;

use App\Models\Conversation;
use App\Models\User;

class ConversationPolicy
{
    /*
    |--------------------------------------------------------------------------
    | عرض قائمة المحادثات
    |--------------------------------------------------------------------------
    */

    public function viewAny(User $user): bool
    {
        return in_array(
            $user->role,
            [
                'admin',
                'engineer',
                'customer',
            ],
            true
        );
    }

    /*
    |--------------------------------------------------------------------------
    | فتح محادثة محددة
    |--------------------------------------------------------------------------
    */

    public function view(
        User $user,
        Conversation $conversation
    ): bool {
        /*
        |--------------------------------------------------------------------------
        | المدير
        |--------------------------------------------------------------------------
        |
        | المدير يستطيع فتح المحادثات المباشرة التي يشارك فيها،
        | ويستطيع فتح محادثات الاستشارات للإدارة والمتابعة.
        |
        */

        if ($user->role === 'admin') {
            if ($conversation->type === 'consultation') {
                return true;
            }

            return $conversation->hasParticipant(
                $user->id
            );
        }

        /*
        |--------------------------------------------------------------------------
        | يجب أن يكون المستخدم مشاركًا
        |--------------------------------------------------------------------------
        */

        if (! $conversation->hasParticipant($user->id)) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | المحادثة المباشرة
        |--------------------------------------------------------------------------
        |
        | المهندس أو العميل يستطيعان فتح المحادثة المباشرة فقط
        | عندما يكون المدير مشاركًا معهم فيها.
        |
        */

        if ($conversation->type === 'direct') {
            return $conversation
                ->participants()
                ->where('users.role', 'admin')
                ->exists();
        }

        /*
        |--------------------------------------------------------------------------
        | محادثة الاستشارة
        |--------------------------------------------------------------------------
        */

        if ($conversation->type !== 'consultation') {
            return false;
        }

        $consultation = $conversation->consultation;

        if (! $consultation) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | شرط الدفع
        |--------------------------------------------------------------------------
        */

        if ($consultation->payment_status !== 'paid') {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | صلاحية العميل
        |--------------------------------------------------------------------------
        */

        if ($user->role === 'customer') {
            return (int) $consultation->customer_id
                === (int) $user->id;
        }

        /*
        |--------------------------------------------------------------------------
        | صلاحية المهندس
        |--------------------------------------------------------------------------
        */

        if ($user->role === 'engineer') {
            return (int) $consultation->engineer_id
                === (int) $user->id;
        }

        return false;
    }

    /*
    |--------------------------------------------------------------------------
    | إرسال الرسائل
    |--------------------------------------------------------------------------
    */

    public function sendMessage(
        User $user,
        Conversation $conversation
    ): bool {
        return $this->view(
            $user,
            $conversation
        );
    }

    /*
    |--------------------------------------------------------------------------
    | تحميل الملفات والتسجيلات
    |--------------------------------------------------------------------------
    */

    public function downloadAttachment(
        User $user,
        Conversation $conversation
    ): bool {
        return $this->view(
            $user,
            $conversation
        );
    }

    /*
    |--------------------------------------------------------------------------
    | بدء محادثة مباشرة
    |--------------------------------------------------------------------------
    |
    | المدير فقط يستطيع إنشاء محادثة مباشرة.
    |
    */

    public function createDirect(User $user): bool
    {
        return $user->role === 'admin';
    }

    /*
    |--------------------------------------------------------------------------
    | إنشاء محادثة استشارة
    |--------------------------------------------------------------------------
    |
    | تُنشأ من النظام بعد تأكيد الدفع، وليس يدويًا من العميل.
    |
    */

    public function createConsultation(
        User $user
    ): bool {
        return $user->role === 'admin';
    }

    /*
    |--------------------------------------------------------------------------
    | حذف المحادثة
    |--------------------------------------------------------------------------
    */

    public function delete(
        User $user,
        Conversation $conversation
    ): bool {
        return $user->role === 'admin';
    }
}
