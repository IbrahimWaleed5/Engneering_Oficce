    /**
     * يحدد هل النص يبدو كحادث أمني يحتاج موظف دعم.
     */
    public function requiresSecurityEscalation(
        string $message
    ): bool {
        $normalized =
            $this->normalizeArabicText($message);

        $securityPatterns = [
            'انسرق حساب',
            'سرق حساب',
            'حسابي انسرق',
            'حسابي مخترق',
            'اخترق حساب',
            'اختراق حساب',
            'تهكير حساب',
            'هكر حساب',
            'دخل على حسابي',
            'دخول غير مصرح',
            'مش انا دخلت',
            'تسجيل دخول غريب',
            'كلمه السر انسرقت',
            'كلمه المرور انسرقت',
            'الباسورد انسرق',
            'رمز التحقق',
            'كود التحقق',
            'otp',
            'تسريب بيانات',
            'بياناتي تسربت',
            'كشف بيانات',
            'بيانات مستخدم اخر',
            'بيانات عميل اخر',
            'بيانات شخص اخر',
            'تغيير صلاحيات',
            'ارفع صلاحيتي',
            'اعطيني صلاحيات',
            'تجاوز الحمايه',
            'تجاوز النظام',
            'ثغره امنيه',
            'ثغره بالنظام',
            'عمليه مشبوهه',
            'دفع مشبوه',
            'خصم مشبوه',
            'دفعة مشبوهة',
            'انتحال هويه',
        ];

        foreach ($securityPatterns as $pattern) {
            if (
                Str::contains(
                    $normalized,
                    $this->normalizeArabicText(
                        $pattern
                    )
                )
            ) {
                return true;
            }
        }

        return false;
    }

    /**
     * معلومات مختصرة عن المستخدم الحالي بدون بيانات حساسة.
     */
    public function buildUserContext(
        mixed $user
    ): string {
        if (! $user) {
            return implode("\n", [
                'نوع الزائر: زائر غير مسجل الدخول.',
                'لا تفترض وجود طلبات أو استشارات أو دفعات خاصة به.',
                'إذا احتاج خدمة تتطلب حسابًا، اطلب منه تسجيل الدخول أو إنشاء حساب.',
            ]);
        }

        $warningsCount =
            (int) ($user->warnings_count ?? 0);

        $remaining = max(
            0,
            3 - $warningsCount
        );

        return implode("\n", [
            'المستخدم مسجل الدخول.',
            'الدور: ' .
                ($user->role ?? 'غير محدد'),
            'حالة الحساب: ' .
                ($user->status ?? 'غير محددة'),
            'عدد المخالفات المؤكدة: ' .
                $warningsCount,
            'المتبقي حتى حد التعليق: ' .
                $remaining,
            'لا تكشف أي بيانات حساسة أو معلومات لا تخص هذا المستخدم.',
        ]);
    }

    /**
     * إرجاع أكثر المقالات ارتباطًا بالسؤال.
     */
    public function findRelevantArticles(
        string $message,
        int $limit = 8
    ): Collection {
        $limit = max(
            1,
            min($limit, 12)
        );

        $words = $this->extractWords($message);

        if ($words->isEmpty()) {
            return collect();
        }

        $articles = KnowledgeBaseArticle::query()
            ->where('is_active', true)
            ->get();

        return $articles
            ->map(function (
                KnowledgeBaseArticle $article
            ) use ($words) {
                return [
                    'article' => $article,
                    'score' =>
                        $this->calculateScore(
                            $article,
                            $words
                        ),
                ];
            })
            ->filter(
                fn (array $item) =>
                    $item['score'] > 0
            )
            ->sortByDesc('score')
            ->take($limit)
            ->pluck('article')
            ->values();
    }

    private function calculateScore(
        KnowledgeBaseArticle $article,
        Collection $words
    ): float {
        $questionText =
            $this->normalizeArabicText(
                (string) $article->question
            );

        $keywordsText =
            $this->normalizeArabicText(
                $this->normalizeKeywords(
                    $article->keywords
                )
            );

        $answerText =
            $this->normalizeArabicText(
                (string) $article->answer
            );

        $score = 0;

        foreach ($words as $word) {
            if (
                Str::contains(
                    $questionText,
                    $word
                )
            ) {
                $score += 4;
            }

            if (
                Str::contains(
                    $keywordsText,
                    $word
                )
            ) {
                $score += 3;
            }

            if (
                Str::contains(
                    $answerText,
                    $word
                )
            ) {
                $score += 1;
            }
        }

        if (
            isset($article->priority)
            && is_numeric($article->priority)
        ) {
            $score +=
                ((float) $article->priority) * 0.1;
        }

        return $score;
    }

    private function normalizeKeywords(
        mixed $keywords
    ): string {
        if (is_array($keywords)) {
            return collect($keywords)
                ->filter()
                ->map(
                    fn ($keyword) =>
                        trim((string) $keyword)
                )
                ->implode(', ');
        }

        if (! is_string($keywords)) {
            return '';
        }

        $keywords = trim($keywords);

        if ($keywords === '') {
            return '';
        }

        $decoded = json_decode(
            $keywords,
            true
        );

        if (
            json_last_error()
                === JSON_ERROR_NONE
            && is_array($decoded)
        ) {
            return collect($decoded)
                ->filter()
                ->map(
                    fn ($keyword) =>
                        trim((string) $keyword)
                )
                ->implode(', ');
        }

        return $keywords;
    }

    private function extractWords(
        string $message
    ): Collection {
        $message =
            $this->normalizeArabicText(
                $message
            );

        $message = preg_replace(
            '/[^\p{Arabic}\p{L}\p{N}\s]/u',
            ' ',
            $message
        );

        $ignoredWords = [
            'كيف',
            'شو',
            'ماذا',
            'وين',
            'اين',
            'هل',
            'في',
            'من',
            'على',
            'الي',
            'الى',
            'عن',
            'انا',
            'بدي',
            'اريد',
            'عندي',
            'ممكن',
            'لو',
            'ما',
            'هو',
            'هي',
            'هذا',
            'هذه',
            'مع',
            'او',
            'ثم',
            'كل',
            'اي',
            'ليش',
            'ليه',
            'طريقه',
        ];

        return collect(
            preg_split(
                '/\s+/u',
                $message
            )
        )
            ->map(
                fn ($word) =>
                    trim((string) $word)
            )
            ->filter(
                fn ($word) =>
                    mb_strlen($word) >= 2
            )
            ->reject(
                fn ($word) =>
                    in_array(
                        $word,
                        $ignoredWords,
                        true
                    )
            )
            ->unique()
            ->values();
    }

    private function normalizeArabicText(
        string $text
    ): string {
        $text = Str::lower(
            trim($text)
        );

        return str_replace(
            [
                'أ',
                'إ',
                'آ',
                'ة',
                'ى',
                'ؤ',
                'ئ',
            ],
            [
                'ا',
                'ا',
                'ا',
                'ه',
                'ي',
                'و',
                'ي',
            ],
            $text
        );
    }
